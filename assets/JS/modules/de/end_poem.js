function startPoem() {
    if (isPlaying) return;
    playerName = playerNameInput.value.trim() || 'Player';
    resetPoemState();
    isPlaying = true;
    processPoemText();
    document.querySelector('#poem').scrollIntoView({ behavior: 'smooth' });
    setTimeout(() => {
        startScrolling();
        animateLines();
        showToast(
            t('toast_poem_started'),
            t('toast_poem_started_message', { name: playerName }),
            'success'
        );
        playClickSound();
    }, 1000);
}

function resetPoemState() {
    clearInterval(scrollInterval);
    scrollInterval = null;
    isPaused = false;
    currentScrollPosition = 0;
    poemLines = [];
    visibleLineCounter = 0;
    poemText.innerHTML = '';
    poemScroll.style.transform = 'translateY(100%)';
    poemScroll.style.transition = 'transform 0.05s linear';
    repeatSection.classList.add('hidden');
    pauseBtn.innerHTML = '<i class="fas fa-pause"></i> ' + t('end_pause');
}

function processPoemText() {
    const poemFullText = getPoemText();
    let processedText = poemFullText.replace(/SPIELERNAME/g, playerName);
    processedText = processedText.replace(/PLAYERNAME/g, playerName);
    const lines = processedText.split('\n');
    poemText.innerHTML = '';
    poemLines = [];
    visibleLineCounter = 0;
    lines.forEach((line, index) => {
        const lineDiv = document.createElement('div');
        lineDiv.className = 'poem-line';
        if (line.trim() === '') {
            lineDiv.classList.add('empty');
            lineDiv.innerHTML = '&nbsp;';
        } else {
            lineDiv.textContent = line;
            if (line.includes(playerName) && playerName !== 'PLAYERNAME') {
                lineDiv.classList.add('player-name');
            }
            if (line.includes('[scrambled]')) {
                lineDiv.classList.add('scrambled');
            }
            if (visibleLineCounter % 2 === 0) {
                lineDiv.classList.add('turquoise');
            } else {
                lineDiv.classList.add('dark-green');
            }
            visibleLineCounter++;
        }
        lineDiv.style.transitionDelay = `${index * 0.05}s`;
        poemText.appendChild(lineDiv);
        poemLines.push(lineDiv);
    });
    setTimeout(() => {
        const contentHeight = poemText.offsetHeight;
        const containerHeight = poemScroll.parentElement.offsetHeight;
        maxScrollHeight = contentHeight + containerHeight;
    }, 100);
}

function startScrolling() {
    if (scrollInterval) clearInterval(scrollInterval);
    scrollInterval = setInterval(() => {
        if (!isPaused && isPlaying) {
            const scrollStep = scrollSpeed / 60;
            currentScrollPosition += scrollStep;
            const scrollPercent = (currentScrollPosition / maxScrollHeight) * 100;
            poemScroll.style.transform = `translateY(calc(100% - ${Math.min(scrollPercent, 100)}%))`;
            if (currentScrollPosition >= maxScrollHeight) {
                endPoem();
            }
        }
    }, 1000 / 60);
}

function animateLines() {
    let delay = 0;
    poemLines.forEach(line => {
        setTimeout(() => {
            line.classList.add('visible');
        }, delay);
        delay += 50;
    });
}

function togglePause() {
    if (!isPlaying) return;
    isPaused = !isPaused;
    if (isPaused) {
        pauseBtn.innerHTML = '<i class="fas fa-play"></i> ' + t('end_resume');
        showToast(
            t('toast_poem_paused'),
            t('toast_poem_paused_message'),
            'info'
        );
    } else {
        pauseBtn.innerHTML = '<i class="fas fa-pause"></i> ' + t('end_pause');
        showToast(
            t('toast_poem_resumed'),
            t('toast_poem_resumed_message'),
            'info'
        );
    }
    playClickSound();
}

function restartPoem() {
    if (!isPlaying) return;
    clearInterval(scrollInterval);
    currentScrollPosition = 0;
    poemScroll.style.transform = 'translateY(100%)';
    poemLines.forEach(line => line.classList.remove('visible'));
    setTimeout(() => {
        startScrolling();
        animateLines();
        showToast(
            t('toast_poem_restarted'),
            t('toast_poem_restarted_message'),
            'info'
        );
        playClickSound();
    }, 500);
}

function resetPoem() {
    clearInterval(scrollInterval);
    scrollInterval = null;
    isPlaying = false;
    isPaused = false;
    currentScrollPosition = 0;
    visibleLineCounter = 0;
    poemText.innerHTML = '';
    poemLines = [];
    poemScroll.style.transform = 'translateY(100%)';
    repeatSection.classList.add('hidden');
    pauseBtn.innerHTML = '<i class="fas fa-pause"></i> ' + t('end_pause');
    showToast(
        t('toast_poem_reset'),
        t('toast_poem_reset_message'),
        'info'
    );
    playClickSound();
}

function repeatPoem() {
    repeatSection.classList.add('hidden');
    resetPoem();
    setTimeout(startPoem, 500);
    playClickSound();
}

function setScrollSpeed(speed) {
    scrollSpeed = speed;
    if (isPlaying && !isPaused) {
        clearInterval(scrollInterval);
        startScrolling();
    }
}

function endPoem() {
    clearInterval(scrollInterval);
    isPlaying = false;
    setTimeout(() => {
        repeatSection.classList.remove('hidden');
        repeatSection.scrollIntoView({ behavior: 'smooth' });
        showToast(
            t('toast_poem_ended'),
            t('toast_poem_ended_message'),
            'info'
        );
        playClickSound();
    }, 1000);
}

